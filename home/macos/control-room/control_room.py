def windows(cfg: dict) -> list[dict]:
    fmt = "%{window-id}|%{app-name}|%{workspace}|%{window-title}"
    proc = aerospace(cfg, "list-windows", "--all", "--format", fmt)
    rows = []
    for line in proc.stdout.splitlines():
        parts = line.split("|", 3)
        if len(parts) == 4:
            rows.append({"id": parts[0].strip(), "app": parts[1].strip(),
                         "workspace": parts[2].strip(), "title": parts[3].strip()})
    return rows


def focus_ai(cfg: dict) -> None:
    aerospace(cfg, "workspace", cfg.get("aiSpace", "1AI"))


def cmd_desk(cfg: dict, profile: str) -> str:
    desks, apps = cfg["desks"], cfg["apps"]
    ai_space = cfg.get("aiSpace", "1AI")
    if profile in ("reset", "normal", "home"):
        moved = 0
        for w in windows(cfg):
            for app in apps.values():
                if app.get("name") == w["app"] and app.get("space") \
                        and w["workspace"] != app["space"]:
                    aerospace(cfg, "move-node-to-workspace", "--window-id",
                              w["id"], app["space"])
                    moved += 1
        focus_ai(cfg)
        return f"Desk reset, {moved} windows sent home."
    desk = desks.get(profile)
    if desk is None:
        return f"No desk called {profile}."
    reset_first = desk.get("resetFirst", True)
    if reset_first:
        cmd_desk(cfg, "reset")
    pulled = 0
    for key in desk.get("pull", []):
        app = apps.get(key, {"name": key})
        if not any(w["app"] == app["name"] for w in windows(cfg)):
            run(["open", "-a", app["name"]], timeout=15)
            time.sleep(1.5)
        for w in windows(cfg):
            if w["app"] == app["name"]:
                aerospace(cfg, "move-node-to-workspace", "--window-id", w["id"],
                          ai_space)
                pulled += 1
                break
    focus_ai(cfg)
    if desk.get("layout"):
        aerospace(cfg, "layout", *desk["layout"].split())
    return f"Desk {profile}: {pulled} apps beside the control room."


def app_for(cfg: dict, spoken: str) -> dict | None:
    spoken = normalise(spoken)
    for key, app in cfg["apps"].items():
        names = [key, app.get("name", "")] + app.get("aliases", [])
        if spoken in {normalise(n) for n in names if n}:
            return app
    return None


