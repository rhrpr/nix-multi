CONFIG_PATH = Path(
    os.environ.get(
        "CONTROL_ROOM_CONFIG",
        Path.home() / ".config" / "control-room" / "config.json",
    )
)
STATE_DIR = Path(
    os.environ.get(
        "CONTROL_ROOM_STATE", Path.home() / ".local" / "state" / "control-room"
    )
)
DRY_RUN = os.environ.get("CONTROL_ROOM_DRY_RUN") == "1"

# Agent kinds Herdr can launch natively with `herdr agent start --kind`.
NATIVE_KINDS = {
    "pi", "claude", "codex", "gemini", "cursor", "devin", "agy", "cline", "omp",
    "mastracode", "opencode", "copilot", "kimi", "kiro", "droid", "amp", "grok",
    "hermes", "kilo", "qodercli", "qwen", "letta", "maki", "muse",
}

# Arguments that continue the most recent conversation in the pane's cwd.
# Used only when a restored pane came back as a bare shell (`up --revive`).
CONTINUE_ARGS = {
    "claude": ["--continue"],
    "codex": ["resume", "--last"],
    "copilot": ["--continue"],
    "opencode": ["--continue"],
}

STATUS_ICON = {
    "working": ("33", "● working"),
    "blocked": ("31;1", "▲ BLOCKED"),
    "done": ("32", "✔ done"),
    "idle": ("2", "○ idle"),
    "unknown": ("35", "? unknown"),
}


def badge(status: str, width: int = 11) -> str:
    colour, text = STATUS_ICON.get(status, ("0", status))
    return f"\033[{colour}m{text:<{width}}\033[0m"


