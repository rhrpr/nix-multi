#!/usr/bin/env python3
"""control-room — one-screen AI control room on top of Herdr + AeroSpace.

Herdr owns the terminals (panes, agents, restore after reboot). AeroSpace owns
desktop windows. This tool is the glue:

  control-room up [--revive]      create any missing project workspaces/panes
  control-room boot               login-time bring-up (attach, restore, apps)
  control-room status [--speak]   one-line fleet summary (and macOS speech)
  control-room dash               live dashboard for the HQ pane
  control-room focus <target>     jump to a project, agent or desktop space
  control-room desk <profile>     pull apps next to the control room / reset
  control-room voice <text...>    route a spoken command (also --audio FILE)
  control-room transcribe FILE    speech-to-text only (used for dictation)
  control-room voice-setup        download the local Whisper model
  control-room doctor             check every dependency and permission

Configuration is generated by Nix at ~/.config/control-room/config.json.
Only the Python standard library is used.
"""

