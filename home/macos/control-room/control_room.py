@dataclass
class Action:
    kind: str                  # prompt|keys|focus|space|app_open|app_quit|desk|...
    target: str | None = None  # pane id / project label / app name / space
    text: str | None = None
    keys: list[str] = field(default_factory=list)
    say: str = ""


def agent_phrases(cfg: dict, panes: list[PaneView]) -> list[tuple[str, str, dict]]:
    """[(spoken phrase, pane_id, info)], longest phrases first."""
    phrases: list[tuple[str, str, dict]] = []
    by_label = {p.label: p for p in panes if p.label}
    for proj in cfg["projects"]:
        proj_words = [proj["name"]] + proj["aliases"]
        first_agent = None
        for spec in proj["panes"]:
            name = agent_name(proj, spec)
            pv = by_label.get(name)
            if pv is None:
                continue
            info = {"name": name, "agent": pv.agent, "project": proj["name"]}
            if first_agent is None and (spec.get("kind") or spec.get("command")):
                first_agent = (pv.pane_id, info)
            for pw in proj_words:
                for aw in [spec["name"], *spec["aliases"]]:
                    phrases.append((normalise(f"{pw} {aw}"), pv.pane_id, info))
            for aw in spec["aliases"]:
                if spec.get("globalAlias"):
                    phrases.append((normalise(aw), pv.pane_id, info))
        if first_agent:
            for pw in proj_words:
                phrases.append((normalise(pw), first_agent[0], first_agent[1]))
    # Agents launched by hand that Herdr has a name for.
    for p in panes:
        if p.name:
            phrases.append((normalise(p.name.replace("-", " ")), p.pane_id,
                            {"name": p.name, "agent": p.agent}))
    phrases.sort(key=lambda t: len(t[0]), reverse=True)
    return phrases


def match_prefix(text: str, phrases: list[tuple[str, str, dict]]):
    for phrase, pane_id, info in phrases:
        if phrase and (text == phrase or text.startswith(phrase + " ")):
            return pane_id, info, text[len(phrase):].strip()
    return None


def space_for(cfg: dict, spoken: str) -> str | None:
    spoken = normalise(spoken)
    for key, space in cfg["spaces"].items():
        aliases = [key] + (space.get("aliases", []) if isinstance(space, dict) else [])
        if spoken in {normalise(a) for a in aliases}:
            return space["name"] if isinstance(space, dict) else space
    return None


VERB_FOCUS = r"(?:go to|goto|switch to|show me|show|focus|open up|jump to)"
VERB_PROMPT = r"(?:tell|ask|prompt|send)"


def parse(text: str, cfg: dict, panes: list[PaneView]) -> Action | None:
    t = normalise(text)
    t = re.sub(r"^(?:hey |ok |okay )?(?:control room |computer )", "", t).strip()
    t = re.sub(r"\b(?:please|thanks|thank you)\b", "", t).strip()
    if not t:
        return None
    phrases = agent_phrases(cfg, panes)

    if re.fullmatch(r"(?:status|report|status report|sitrep|what'?s happening|"
                    r"who'?s blocked|how are we doing|fleet status)", t):
        return Action("status")
    if re.fullmatch(r"(?:control room|dashboard|agents|show agents|home base|hq)", t):
        return Action("focus_ai", say="Control room.")

    m = re.fullmatch(r"(?:desk|layout|mode|desktop) (.+)", t) or \
        re.fullmatch(r"(.+) (?:desk|mode|layout)", t)
    if m:
        return Action("desk", target=m.group(1).strip())

    m = re.fullmatch(r"(?:new|spawn|start|add|launch) (?:a |an )?(\w+)"
                     r"(?: agent)? (?:in|for|on|at) (.+)", t)
    if m and m.group(1) in NATIVE_KINDS | {"gemini"}:
        proj = next((p for p in cfg["projects"]
                     if normalise(m.group(2)) in
                     {normalise(x) for x in [p["name"], *p["aliases"]]}), None)
        if proj:
            return Action("spawn", target=proj["name"], text=m.group(1))

    m = re.fullmatch(r"(?:approve|accept|confirm|yes) (.+)", t) or \
        re.fullmatch(r"(.+) (?:approve|approved|accept|yes|go ahead)", t)
    if m and (hit := match_prefix(m.group(1), phrases)) and not hit[2]:
        return Action("keys", target=hit[0], keys=["enter"],
                      say=f"Approved {hit[1]['name']}.")
    m = re.fullmatch(r"(?:deny|reject|decline|stop|interrupt|cancel|escape|pause) (.+)", t)
    if m and (hit := match_prefix(m.group(1), phrases)) and not hit[2]:
        return Action("keys", target=hit[0], keys=["esc"],
                      say=f"Interrupted {hit[1]['name']}.")
    m = re.fullmatch(r"(?:read|what did|what is|what'?s) (.+?)(?: say| saying| doing)?", t)
    if m and (hit := match_prefix(m.group(1), phrases)) and not hit[2]:
        return Action("read", target=hit[0], text=hit[1]["name"])

    m = re.fullmatch(rf"{VERB_FOCUS} (.+)", t)
    if m:
        target = m.group(1)
        if target in ("control room", "the control room", "dashboard", "agents", "hq"):
            return Action("focus_ai")
        if (space := space_for(cfg, target)):
            return Action("space", target=space)
        proj = next((p for p in cfg["projects"]
                     if normalise(target) in
                     {normalise(x) for x in [p["name"], *p["aliases"]]}), None)
        if proj:
            return Action("focus_project", target=proj["name"])
        if (hit := match_prefix(target, phrases)) and not hit[2]:
            return Action("focus_agent", target=hit[0], say=hit[1]["name"])
        if (app := app_for(cfg, target)):
            return Action("app_open", target=app["name"])

    m = re.fullmatch(r"(?:open|launch|start|run) (.+)", t)
    if m and not match_prefix(m.group(1), phrases):
        app = app_for(cfg, m.group(1))
        name = app["name"] if app else m.group(1).title()
        return Action("app_open", target=name)
    m = re.fullmatch(r"(?:quit|close|kill) (.+)", t)
    if m and not match_prefix(m.group(1), phrases):
        app = app_for(cfg, m.group(1))
        if app:
            return Action("app_quit", target=app["name"])

    m = re.fullmatch(r"(?:type|dictate|write) (.+)", t)
    if m:
        return Action("type", text=m.group(1))

    m = re.fullmatch(r"(?:all agents|everyone|everybody|broadcast)[, ]+(.+)", t)
    if m:
        return Action("broadcast", text=_original_tail(text, m.group(1)))

    m = re.fullmatch(rf"{VERB_PROMPT} (.+)", t)
    rest = m.group(1) if m else t
    hit = match_prefix(rest, phrases)
    if hit and hit[2]:
        prompt = re.sub(r"^(?:to|that) ", "", hit[2])
        return Action("prompt", target=hit[0], text=_original_tail(text, prompt),
                      say=f"Sent to {hit[1]['name']}.")
    return None


def _original_tail(original: str, normalised_tail: str) -> str:
    """Recover the user's original casing/punctuation for the prompt body."""
    words = normalised_tail.split()
    if not words:
        return normalised_tail
    pattern = r"\W*".join(re.escape(w) for w in words[:3])
    m = re.search(pattern, original, flags=re.IGNORECASE)
    return original[m.start():].strip() if m else normalised_tail


def llm_rewrite(cfg: dict, text: str, panes: list[PaneView]) -> str | None:
    llm = cfg["voice"].get("llm", {})
    if not llm.get("enable"):
        return None
    names = sorted({info["name"] for _, _, info in agent_phrases(cfg, panes)})
    system = (
        "You convert a spoken request into ONE command for a terminal control "
        "room. Reply with the command only, no quotes. Grammar:\n"
        "  status | control room | desk <name> | go to <project|space|app>\n"
        "  open <app> | quit <app> | approve <agent> | stop <agent> | read <agent>\n"
        "  new <claude|codex|gemini> in <project> | <agent> <prompt text>\n"
        f"Agents (say with spaces, not dashes): {', '.join(n.replace('-', ' ') for n in names)}\n"
        f"Projects: {', '.join(p['name'] for p in cfg['projects'])}\n"
        f"Spaces: {', '.join(cfg['spaces'])}\nDesks: {', '.join(cfg['desks'])}\n"
        "If nothing fits reply NONE."
    )
    body = json.dumps({
        "model": llm.get("model", "local"),
        "temperature": 0,
        "max_tokens": 120,
        "messages": [{"role": "system", "content": system},
                     {"role": "user", "content": text}],
    }).encode()
    req = urllib.request.Request(llm.get("url", "http://localhost:1234/v1/chat/completions"),
                                 data=body, headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=float(llm.get("timeout", 12))) as resp:
            out = json.load(resp)["choices"][0]["message"]["content"].strip()
    except Exception as exc:  # noqa: BLE001 - any failure means "no rewrite"
        log(f"llm fallback unavailable: {exc}")
        return None
    out = re.sub(r"<think>.*?</think>", "", out, flags=re.S).strip().splitlines()
    out = out[-1].strip() if out else ""
    return None if not out or out.upper() == "NONE" else out


def execute(cfg: dict, act: Action) -> dict:
    """Perform an action; returns {"say": str, "type_text": str|None}."""
    say, type_text = act.say, None
    if act.kind == "status":
        say = summary(cfg)[0]
    elif act.kind == "focus_ai":
        focus_ai(cfg)
    elif act.kind == "desk":
        say = cmd_desk(cfg, slug(act.target or ""))
    elif act.kind == "space":
        aerospace(cfg, "workspace", act.target)
    elif act.kind == "focus_project":
        workspaces, _ = fleet(cfg)
        ws = workspaces.get(act.target)
        focus_ai(cfg)
        if ws:
            herdr(cfg, "workspace", "focus", ws["workspace_id"])
            say = act.target
        else:
            say = f"{act.target} is not open. Run control room up."
    elif act.kind == "focus_agent":
        focus_ai(cfg)
        herdr(cfg, "agent", "focus", act.target) or \
            herdr(cfg, "workspace", "focus", act.target.split(":")[0])
    elif act.kind == "app_open":
        proc = run(["open", "-a", act.target], timeout=15)
        say = f"Opening {act.target}." if proc.returncode == 0 else \
            f"Couldn't find {act.target}."
    elif act.kind == "app_quit":
        run(["osascript", "-e", f'tell application {json.dumps(act.target)} to quit'],
            timeout=10)
        say = f"Quit {act.target}."
    elif act.kind == "keys":
        herdr(cfg, "agent", "send-keys", act.target, *act.keys) or \
            herdr(cfg, "pane", "send-keys", act.target, *act.keys)
    elif act.kind == "read":
        res = run([herdr_bin(cfg), "agent", "read", act.target, "--source",
                   "recent-unwrapped", "--lines", "12"], timeout=10)
        lines = [ln.strip() for ln in res.stdout.splitlines() if ln.strip()]
        tail = lines[-3:] if lines else ["nothing yet"]
        notify(f"{act.text}", "\n".join(tail))
        say = f"{act.text} says: {tail[-1][:160]}"
    elif act.kind == "prompt":
        res = herdr(cfg, "agent", "prompt", act.target, act.text or "", timeout=20)
        if res is None:  # not a detected agent (or blocked): type it instead
            _, panes = fleet(cfg)
            pv = next((p for p in panes if p.pane_id == act.target), None)
            if pv and pv.status == "blocked":
                say = "That agent is waiting for approval. Say approve or stop first."
            else:
                herdr(cfg, "pane", "run", act.target, act.text or "")
    elif act.kind == "broadcast":
        _, panes = fleet(cfg)
        sent = 0
        for p in panes:
            if p.agent and p.status in ("idle", "done"):
                if herdr(cfg, "agent", "prompt", p.pane_id, act.text or ""):
                    sent += 1
        say = f"Sent to {sent} idle agents."
    elif act.kind == "spawn":
        say = spawn(cfg, act.target or "", act.text or "claude")
    elif act.kind == "type":
        type_text = act.text
    return {"say": say, "type_text": type_text}


def spawn(cfg: dict, project_name: str, kind: str) -> str:
    project = next(p for p in cfg["projects"] if p["name"] == project_name)
    workspaces, panes = fleet(cfg)
    ws = workspaces.get(project_name)
    if not ws:
        return f"{project_name} is not open."
    mine = [p for p in panes if p.workspace_id == ws["workspace_id"]]
    target = next((p for p in mine if p.focused), None) or (mine[-1] if mine else None)
    if not target:
        return "No pane to split."
    res = herdr(cfg, "pane", "split", target.pane_id, "--direction", "right",
                "--cwd", project["path"], "--no-focus")
    if not res:
        return "Split failed."
    n = sum(1 for p in mine if (p.agent or "") == kind) + 1
    spec = {"name": f"{kind}{n}", "kind": None if kind == "gemini" else kind,
            "command": "cr-gemini" if kind == "gemini" else None,
            "args": [], "aliases": []}
    launch_pane(cfg, project, spec, res["pane"]["pane_id"])
    return f"Started {kind} {n} in {project_name}."


def whisper_prompt(cfg: dict) -> str:
    words = {"claude", "codex", "gemini", "status", "approve", "desk"}
    for p in cfg["projects"]:
        words.add(p["name"])
        words.update(p["aliases"])
    words.update(cfg["desks"])
    return ", ".join(sorted(words))


def transcribe(cfg: dict, audio: str) -> str:
    voice = cfg["voice"]
    model = os.path.expanduser(voice.get("modelPath", ""))
    if not os.path.exists(model):
        return ""
    proc = run([voice.get("whisper", "whisper-cli"), "-m", model, "-f", audio,
                "-l", voice.get("language", "en"), "-nt", "-np",
                "--prompt", whisper_prompt(cfg)], timeout=60)
    text = " ".join(proc.stdout.split())
    text = re.sub(r"\[[^\]]*\]|\([^)]*\)", " ", text).strip()
    if normalise(text) in {"", "you", "thank you", "thanks for watching", "bye"}:
        return ""
    return text


def cmd_voice(cfg: dict, words: list[str], audio: str | None, as_json: bool) -> int:
    heard = transcribe(cfg, audio) if audio else " ".join(words)
    result = {"heard": heard, "ok": False, "say": "", "type_text": None}
    if not heard:
        result["say"] = "Didn't hear anything." if audio and \
            os.path.exists(os.path.expanduser(cfg["voice"].get("modelPath", ""))) \
            else "No speech model yet. Run control room voice setup."
    else:
        _, panes = fleet(cfg)
        act = parse(heard, cfg, panes)
        via = "grammar"
        if act is None and (rewritten := llm_rewrite(cfg, heard, panes)):
            act, via = parse(rewritten, cfg, panes), f"llm:{rewritten}"
        if act is None:
            result["say"] = f"Not sure what to do with: {heard}"
        else:
            result.update(execute(cfg, act))
            result["ok"] = True
            result["action"] = act.kind
            result["via"] = via
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    with open(STATE_DIR / "voice.log", "a", encoding="utf-8") as fh:
        stamp = _dt.datetime.now().strftime("%H:%M")
        fh.write(f"{stamp} “{heard}” → {result.get('action', '—')} {result['say']}\n")
    if as_json:
        print(json.dumps(result))
    else:
        print(result["say"] or result.get("action", ""))
    if result["say"] and not as_json and result.get("action") == "status":
        speak(cfg, result["say"])
    return 0 if result["ok"] else 1


def cmd_voice_setup(cfg: dict) -> int:
    voice = cfg["voice"]
    model = Path(os.path.expanduser(voice.get("modelPath")))
    model.parent.mkdir(parents=True, exist_ok=True)
    if model.exists():
        print(f"model present: {model}")
        return 0
    name = voice.get("model", "small.en")
    print(f"downloading whisper model {name} -> {model.parent}")
    proc = subprocess.run([voice.get("downloader", "whisper-cpp-download-ggml-model"),
                           name, str(model.parent)])
    return proc.returncode


