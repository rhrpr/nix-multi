def wait_for(fn, timeout: float, step: float = 1.0) -> bool:
    end = time.time() + timeout
    while time.time() < end:
        if fn():
            return True
        time.sleep(step)
    return False


def client_running() -> bool:
    return run(["pgrep", "-f", "control-room-attach"], timeout=5).returncode == 0


def cmd_attach_window(cfg: dict) -> None:
    term = cfg.get("terminal", {})
    if client_running():
        return
    app = term.get("app", "Ghostty")
    args = [f"--title={term.get('title', 'Control Room')}",
            f"--command={term.get('attach', 'control-room-attach')}"]
    args += term.get("extraArgs", [])
    run(["open", "-na", app, "--args", *args], timeout=20)


def cmd_boot(cfg: dict) -> int:
    log("boot: start")
    boot = cfg.get("boot", {})
    time.sleep(float(boot.get("initialDelay", 3)))
    for app in boot.get("daemons", ["AeroSpace"]):
        run(["open", "-g", "-a", app], timeout=20)
    wait_for(lambda: aerospace(cfg, "list-workspaces", "--focused").returncode == 0, 60)
    cmd_attach_window(cfg)  # starting a client starts/restores the Herdr server
    ok = wait_for(lambda: herdr(cfg, "workspace", "list", timeout=5) is not None, 90, 2)
    if not ok:
        notify("Control room", "Herdr did not come up — open a terminal and run herdr")
        log("boot: herdr unreachable")
        return 1
    time.sleep(float(boot.get("settleSeconds", 10)))  # let native resumes land
    cmd_up(cfg, revive=bool(boot.get("revive", True)), quiet=True)
    for key in boot.get("apps", []):
        app = cfg["apps"].get(key, {"name": key})
        run(["open", "-g", "-a", app["name"]], timeout=20)
    time.sleep(2)
    focus_ai(cfg)
    text, _ = summary(cfg)
    notify("Control room online", text)
    log(f"boot: done — {text}")
    return 0


def cmd_doctor(cfg: dict) -> int:
    bad = 0

    def check(ok: bool, label: str, hint: str = "") -> None:
        nonlocal bad
        print(("[ok]   " if ok else "[fail] ") + label + ("" if ok else f"  → {hint}"))
        bad += 0 if ok else 1

    for tool in [herdr_bin(cfg), cfg.get("aerospace", "aerospace")]:
        check(shutil.which(tool) is not None, f"{tool} on PATH", "rebuild / brew bundle")
    for proj in cfg["projects"]:
        check(os.path.isdir(proj["path"]), f"project {proj['name']}: {proj['path']}",
              "clone it or fix programs.controlRoom.projects")
        for pane in proj["panes"]:
            exe = pane.get("command", "").split()[0] if pane.get("command") else pane.get("kind")
            if exe:
                check(shutil.which(exe) is not None, f"  {exe} for {proj['name']}/{pane['name']}",
                      "install the CLI")
    check(herdr(cfg, "workspace", "list", timeout=5) is not None, "Herdr server reachable",
          "run `herdr` once")
    check(aerospace(cfg, "list-workspaces", "--focused").returncode == 0,
          "AeroSpace running", "open -a AeroSpace and grant Accessibility")
    voice = cfg["voice"]
    if voice.get("enable", True):
        check(os.path.exists(os.path.expanduser(voice.get("modelPath", ""))),
              "Whisper model", "control-room voice-setup")
        check(shutil.which(voice.get("whisper", "whisper-cli")) is not None, "whisper-cli")
        check(shutil.which(voice.get("sox", "sox")) is not None, "sox (recorder)")
        check(os.path.isdir("/Applications/Hammerspoon.app"), "Hammerspoon installed",
              "brew install --cask hammerspoon; grant Accessibility + Microphone")
    out = run([herdr_bin(cfg), "integration", "status"], timeout=10).stdout
    check("claude" in out, "Herdr agent integrations", "herdr-agent-setup")
    return 1 if bad else 0


