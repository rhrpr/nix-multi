def log(msg: str) -> None:
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    stamp = _dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    with open(STATE_DIR / "control-room.log", "a", encoding="utf-8") as fh:
        fh.write(f"{stamp} {msg}\n")


def load_config() -> dict:
    try:
        with open(CONFIG_PATH, encoding="utf-8") as fh:
            cfg = json.load(fh)
    except FileNotFoundError:
        sys.exit(f"control-room: missing {CONFIG_PATH}; rebuild your Nix config")
    cfg.setdefault("projects", [])
    cfg.setdefault("apps", {})
    cfg.setdefault("spaces", {})
    cfg.setdefault("desks", {})
    cfg.setdefault("voice", {})
    for proj in cfg["projects"]:
        proj["path"] = os.path.expanduser(proj["path"])
        proj.setdefault("aliases", [])
        proj.setdefault("panes", [])
        for pane in proj["panes"]:
            pane.setdefault("aliases", [])
            pane.setdefault("args", [])
            pane.setdefault("kind", None)
            pane.setdefault("command", None)
    return cfg


def run(cmd: list[str], *, check: bool = False, timeout: float | None = 60,
        capture: bool = True) -> subprocess.CompletedProcess:
    if DRY_RUN:
        print("DRY:", shlex.join(cmd))
        return subprocess.CompletedProcess(cmd, 0, '{"result":{}}', "")
    try:
        return subprocess.run(
            cmd, check=check, timeout=timeout, text=True,
            capture_output=capture,
        )
    except FileNotFoundError:
        return subprocess.CompletedProcess(cmd, 127, "", f"{cmd[0]}: not found")
    except subprocess.TimeoutExpired:
        return subprocess.CompletedProcess(cmd, 124, "", "timeout")


def herdr_bin(cfg: dict) -> str:
    return cfg.get("herdr", "herdr")


def herdr(cfg: dict, *args: str, timeout: float = 60) -> dict | None:
    """Run a herdr API command and return its `.result` object, or None."""
    proc = run([herdr_bin(cfg), *args], timeout=timeout)
    if proc.returncode != 0:
        log(f"herdr {' '.join(args)} failed: {proc.stderr.strip()[:300]}")
        return None
    try:
        return json.loads(proc.stdout).get("result", {})
    except (json.JSONDecodeError, AttributeError):
        return {}


def aerospace(cfg: dict, *args: str) -> subprocess.CompletedProcess:
    return run([cfg.get("aerospace", "aerospace"), *args], timeout=10)


def notify(title: str, body: str = "") -> None:
    script = f"display notification {json.dumps(body)} with title {json.dumps(title)}"
    run(["osascript", "-e", script], timeout=5)


def speak(cfg: dict, text: str) -> None:
    if cfg["voice"].get("speak", True) and shutil.which("say"):
        if DRY_RUN:
            print("SAY:", text)
            return
        subprocess.Popen(["say", "-r", "210", text])


def normalise(text: str) -> str:
    text = text.lower().replace("’", "'")
    text = re.sub(r"\[[^\]]*\]|\([^)]*\)", " ", text)  # whisper [BLANK_AUDIO]
    text = re.sub(r"[^a-z0-9' ]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9_-]+", "-", text.lower()).strip("-")[:32] or "x"


def agent_name(project: dict, pane: dict) -> str:
    name = slug(f"{project['name']}-{pane['name']}")
    return name if name[0].isalpha() else f"a{name}"[:32]


