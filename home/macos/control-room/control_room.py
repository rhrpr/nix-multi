@dataclass
class PaneView:
    pane_id: str
    workspace_id: str
    workspace: str
    label: str | None
    agent: str | None
    status: str
    cwd: str | None
    name: str | None = None
    focused: bool = False


def fleet(cfg: dict) -> tuple[dict[str, dict], list[PaneView]]:
    """Return ({workspace_label: workspace}, [panes]) from the live server."""
    ws_res = herdr(cfg, "workspace", "list", timeout=10) or {}
    workspaces = {w.get("label", ""): w for w in ws_res.get("workspaces", [])}
    by_id = {w["workspace_id"]: w.get("label", "") for w in workspaces.values()}
    pane_res = herdr(cfg, "pane", "list", timeout=10) or {}
    agent_res = herdr(cfg, "agent", "list", timeout=10) or {}
    names = {a.get("pane_id"): a.get("name") for a in agent_res.get("agents", [])}
    panes = [
        PaneView(
            pane_id=p["pane_id"],
            workspace_id=p["workspace_id"],
            workspace=by_id.get(p["workspace_id"], p["workspace_id"]),
            label=p.get("label"),
            agent=p.get("agent"),
            status=str(p.get("agent_status", "unknown")).lower(),
            cwd=p.get("foreground_cwd") or p.get("cwd"),
            name=names.get(p["pane_id"]),
            focused=bool(p.get("focused")),
        )
        for p in pane_res.get("panes", [])
    ]
    return workspaces, panes


def grid_splits(count: int) -> list[tuple[int, str, float]]:
    """Split plan for `count` panes: list of (source_index, direction, ratio).

    Pane 0 is the tab's root pane and plan entry i creates pane i+1. The
    result is an evenly sized near-square grid: columns are created first
    (split right), then each column is split down. `ratio` is the share the
    source pane keeps (Herdr's first-child ratio).
    """
    if count <= 1:
        return []
    cols = math.ceil(math.sqrt(count))
    rows_per_col = [count // cols + (1 if c < count % cols else 0) for c in range(cols)]
    plan: list[tuple[int, str, float]] = []
    col_heads = [0]
    for j in range(1, cols):
        plan.append((col_heads[-1], "right", round(1 / (cols - j + 1), 3)))
        col_heads.append(len(plan))
    for c, rows in enumerate(rows_per_col):
        prev = col_heads[c]
        for r in range(1, rows):
            plan.append((prev, "down", round(1 / (rows - r + 1), 3)))
            prev = len(plan)
    return plan


def launch_pane(cfg: dict, project: dict, pane: dict, pane_id: str,
                resume: bool = False, rename: bool = True) -> None:
    name = agent_name(project, pane)
    if rename:
        herdr(cfg, "pane", "rename", pane_id, name, timeout=10)
    kind, command = pane.get("kind"), pane.get("command")
    if command:
        cmd = command + (" --resume" if resume and pane.get("resumeFlag") else "")
        herdr(cfg, "pane", "run", pane_id, cmd, timeout=15)
        return
    if kind in NATIVE_KINDS:
        args = list(pane.get("args", []))
        if resume:
            args = CONTINUE_ARGS.get(kind, []) + args
        extra = ["--", *args] if args else []
        res = herdr(cfg, "agent", "start", name, "--kind", kind, "--pane", pane_id,
                    "--timeout", "60000", *extra, timeout=75)
        if res is None:  # e.g. blocked on a trust prompt; still usable by pane id
            log(f"agent start {name} did not report ready")
        return
    # Plain shell pane: nothing to launch.


SHELLS = {"zsh", "-zsh", "bash", "-bash", "fish", "-fish", "sh", "nu", "login"}


def shell_is_idle(cfg: dict, pane_id: str) -> bool:
    """True when the pane's interactive shell owns the foreground."""
    res = herdr(cfg, "pane", "process-info", "--pane", pane_id, timeout=10)
    if not res:
        return False
    info = res.get("process_info", {})
    fg, shell = info.get("foreground_process_group_id"), info.get("shell_pid")
    if fg is not None and fg == shell:
        return True
    procs = info.get("foreground_processes", [])
    return bool(procs) and all(os.path.basename(p.get("name", "")) in SHELLS
                               for p in procs)


def ensure_project(cfg: dict, project: dict, workspaces: dict[str, dict],
                   panes: list[PaneView], revive: bool) -> list[str]:
    actions: list[str] = []
    label = project["name"]
    specs = project["panes"]
    if label not in workspaces:
        if not os.path.isdir(project["path"]):
            return [f"skip {label}: {project['path']} does not exist"]
        created = herdr(cfg, "workspace", "create", "--cwd", project["path"],
                        "--label", label, "--no-focus")
        if not created:
            return [f"failed to create workspace {label}"]
        root = created["root_pane"]["pane_id"]
        herdr(cfg, "tab", "rename", created["tab"]["tab_id"], "agents")
        pane_ids = [root]
        for source, direction, ratio in grid_splits(len(specs)):
            res = herdr(cfg, "pane", "split", pane_ids[source], "--direction",
                        direction, "--ratio", str(ratio), "--cwd", project["path"],
                        "--no-focus")
            if not res:
                break
            pane_ids.append(res["pane"]["pane_id"])
        for pid, spec in zip(pane_ids, specs):
            herdr(cfg, "pane", "rename", pid, agent_name(project, spec), timeout=10)
        # Agents start in parallel: `agent start` blocks until each is ready.
        with ThreadPoolExecutor(max_workers=max(1, len(pane_ids))) as pool:
            for pid, spec in zip(pane_ids, specs):
                pool.submit(launch_pane, cfg, project, spec, pid, False, False)
        actions.append(f"created {label} with {len(pane_ids)} panes")
        return actions

    # Workspace already exists (normally restored by Herdr after a reboot).
    ws_id = workspaces[label]["workspace_id"]
    mine = {p.label: p for p in panes if p.workspace_id == ws_id and p.label}
    for spec in specs:
        name = agent_name(project, spec)
        pv = mine.get(name)
        if pv is None:
            continue
        if pv.agent and not pv.name and spec.get("kind"):
            herdr(cfg, "agent", "rename", pv.pane_id, name)
            actions.append(f"renamed {pv.pane_id} -> {name}")
        elif revive and not pv.agent and (spec.get("kind") or spec.get("command")) \
                and shell_is_idle(cfg, pv.pane_id):
            launch_pane(cfg, project, spec, pv.pane_id, resume=True)
            actions.append(f"revived {name} in {pv.pane_id}")
    return actions


def cmd_up(cfg: dict, revive: bool = False, quiet: bool = False) -> int:
    workspaces, panes = fleet(cfg)
    if not workspaces and herdr(cfg, "workspace", "list") is None:
        print("control-room: Herdr server is not reachable (run `herdr` first)")
        return 1
    actions: list[str] = []
    if cfg.get("hq", {}).get("enable", True) and "hq" not in workspaces:
        created = herdr(cfg, "workspace", "create", "--cwd", str(Path.home()),
                        "--label", "hq", "--no-focus")
        if created:
            root = created["root_pane"]["pane_id"]
            herdr(cfg, "pane", "rename", root, "hq-dash")
            herdr(cfg, "pane", "run", root, "control-room dash")
            res = herdr(cfg, "pane", "split", root, "--direction", "down",
                        "--ratio", "0.7", "--no-focus")
            if res:
                herdr(cfg, "pane", "rename", res["pane"]["pane_id"], "hq-shell")
            actions.append("created hq")
    elif revive and "hq" in workspaces:
        for p in panes:
            if p.workspace == "hq" and p.label == "hq-dash" \
                    and shell_is_idle(cfg, p.pane_id):
                herdr(cfg, "pane", "run", p.pane_id, "control-room dash")
    for project in cfg["projects"]:
        actions += ensure_project(cfg, project, workspaces, panes, revive)
    for a in actions:
        log(a)
        if not quiet:
            print(a)
    if not actions and not quiet:
        print("control room already up")
    return 0


