def display_name(p: PaneView) -> str:
    return p.name or p.label or f"{p.workspace}:{p.agent or 'shell'}"


def summary(cfg: dict) -> tuple[str, dict[str, list[str]]]:
    _, panes = fleet(cfg)
    groups: dict[str, list[str]] = {}
    for p in panes:
        if p.agent:
            groups.setdefault(p.status, []).append(display_name(p))
    if not groups:
        return "No agents running.", groups
    parts = []
    for status in ("blocked", "done", "working", "idle", "unknown"):
        if status in groups:
            n = len(groups[status])
            names = ", ".join(groups[status]) if status in ("blocked", "done") else ""
            parts.append(f"{n} {status}" + (f": {names}" if names else ""))
    return "; ".join(parts) + ".", groups


def cmd_status(cfg: dict, do_speak: bool, as_json: bool) -> int:
    text, groups = summary(cfg)
    if as_json:
        print(json.dumps({"summary": text, "groups": groups}))
    else:
        print(text)
    if do_speak:
        speak(cfg, text.replace("-", " ").replace(":", ""))
    return 0


def cmd_dash(cfg: dict, interval: float) -> int:
    voice_log = STATE_DIR / "voice.log"
    try:
        while True:
            _, panes = fleet(cfg)
            cols = shutil.get_terminal_size((100, 30)).columns
            out = ["\033[H\033[2J\033[1;35m⌁ CONTROL ROOM\033[0m  "
                   + _dt.datetime.now().strftime("%a %H:%M:%S")]
            out.append("─" * min(cols, 100))
            agents = [p for p in panes if p.agent]
            agents.sort(key=lambda p: (
                ["blocked", "done", "working", "unknown", "idle"].index(p.status)
                if p.status in ("blocked", "done", "working", "unknown", "idle") else 9,
                p.workspace))
            for p in agents:
                where = (p.cwd or "").replace(str(Path.home()), "~")
                out.append(f"{badge(p.status)} "
                           f"{display_name(p):<22.22} {p.agent:<9.9} "
                           f"\033[2m{p.workspace:<12.12} {where[-38:]}\033[0m")
            shells = len(panes) - len(agents)
            out.append("─" * min(cols, 100))
            out.append(f"{len(agents)} agents · {shells} other panes · "
                       f"voice: hold {cfg['voice'].get('commandHotkeyLabel', 'hotkey')}")
            if voice_log.exists():
                out.append("\033[2mrecent voice:\033[0m")
                lines = voice_log.read_text(encoding="utf-8").splitlines()[-6:]
                out += [f"\033[2m  {ln[:cols - 4]}\033[0m" for ln in lines]
            sys.stdout.write("\n".join(out) + "\n")
            sys.stdout.flush()
            time.sleep(interval)
    except KeyboardInterrupt:
        return 0


