def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="control-room", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("up")
    p.add_argument("--revive", action="store_true",
                   help="relaunch agents in restored panes that came back as shells")
    sub.add_parser("boot")
    sub.add_parser("attach-window")
    p = sub.add_parser("status")
    p.add_argument("--speak", action="store_true")
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("dash")
    p.add_argument("--interval", type=float, default=2.0)
    p = sub.add_parser("focus")
    p.add_argument("target", nargs="+")
    p = sub.add_parser("desk")
    p.add_argument("profile")
    p = sub.add_parser("voice")
    p.add_argument("words", nargs="*")
    p.add_argument("--audio")
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("parse", help="show how a phrase would be routed (no side effects)")
    p.add_argument("words", nargs="+")
    p = sub.add_parser("transcribe")
    p.add_argument("audio")
    sub.add_parser("voice-setup")
    sub.add_parser("doctor")
    args = ap.parse_args(argv)
    cfg = load_config()

    if args.cmd == "up":
        return cmd_up(cfg, revive=args.revive)
    if args.cmd == "boot":
        return cmd_boot(cfg)
    if args.cmd == "attach-window":
        cmd_attach_window(cfg)
        return 0
    if args.cmd == "status":
        return cmd_status(cfg, args.speak, args.json)
    if args.cmd == "dash":
        return cmd_dash(cfg, args.interval)
    if args.cmd == "focus":
        _, panes = fleet(cfg)
        act = parse("go to " + " ".join(args.target), cfg, panes)
        if act is None:
            print("unknown target")
            return 1
        print(execute(cfg, act)["say"])
        return 0
    if args.cmd == "desk":
        print(cmd_desk(cfg, args.profile))
        return 0
    if args.cmd == "voice":
        return cmd_voice(cfg, args.words, args.audio, args.json)
    if args.cmd == "parse":
        _, panes = fleet(cfg)
        act = parse(" ".join(args.words), cfg, panes)
        print(json.dumps(act.__dict__ if act else None))
        return 0 if act else 1
    if args.cmd == "transcribe":
        print(transcribe(cfg, args.audio))
        return 0
    if args.cmd == "voice-setup":
        return cmd_voice_setup(cfg)
    if args.cmd == "doctor":
        return cmd_doctor(cfg)
    return 2


if __name__ == "__main__":
    sys.exit(main())
